# Generate a config.h.local from the options configopts.py finds in config.h,
# either everything y, everything n or a random mix. The random one records
# the seed so it can be reproduced with --seed.

import argparse
import os
import random
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from configopts import parse

def main():
    here = os.path.dirname(os.path.abspath(__file__))
    default_config = os.path.join(here, '..', 'config.h')

    ap = argparse.ArgumentParser(description='Generate a config.h.local')
    how = ap.add_mutually_exclusive_group(required=True)
    how.add_argument('--all', choices=['y', 'n'], help='set every option to this')
    how.add_argument('--random', action='store_true', help='set every option randomly')
    ap.add_argument('--seed', type=int, help='seed for --random, printed if not given')
    ap.add_argument('-o', '--output', default='-', help='where to write, default stdout')
    ap.add_argument('config', nargs='?', default=default_config,
                    help='path to config.h (default: the one next to tools/)')
    args = ap.parse_args()

    try:
        options = parse(args.config)
    except OSError as e:
        sys.exit(f'{e.filename}: {e.strerror}')

    if args.random:
        seed = args.seed if args.seed is not None else random.randrange(1 << 32)
        rng = random.Random(seed)
        values = {o['name']: rng.choice(['y', 'n']) for o in options}
        how = f'random, seed {seed}'
        print(f'seed {seed}', file=sys.stderr)
    else:
        values = {o['name']: args.all for o in options}
        how = f'all {args.all}'

    lines = [f'/* Generated by tools/genconfig.py: {how} */']
    lines += [f'#define {name}\t{value}' for name, value in values.items()]
    text = '\n'.join(lines) + '\n'

    if args.output == '-':
        sys.stdout.write(text)
    else:
        with open(args.output, 'w') as f:
            f.write(text)

if __name__ == '__main__':
    main()
